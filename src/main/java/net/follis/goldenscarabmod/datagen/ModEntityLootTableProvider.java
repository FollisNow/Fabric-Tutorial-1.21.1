package net.follis.goldenscarabmod.datagen;

import net.fabricmc.fabric.api.datagen.v1.FabricDataOutput;
import net.fabricmc.fabric.api.datagen.v1.provider.SimpleFabricLootTableProvider;
import net.follis.goldenscarabmod.GoldenScarabMod;
import net.minecraft.item.Items;
import net.minecraft.loot.LootPool;
import net.minecraft.loot.LootTable;
import net.minecraft.loot.context.LootContextTypes;
import net.minecraft.loot.entry.ItemEntry;
import net.minecraft.loot.function.SetCountLootFunction;
import net.minecraft.loot.provider.number.ConstantLootNumberProvider;
import net.minecraft.loot.provider.number.UniformLootNumberProvider;
import net.minecraft.registry.RegistryKey;
import net.minecraft.registry.RegistryKeys;
import net.minecraft.registry.RegistryWrapper;
import net.minecraft.util.Identifier;

import java.util.concurrent.CompletableFuture;
import java.util.function.BiConsumer;

/** Entity loot tables generated by datagen. */
public class ModEntityLootTableProvider extends SimpleFabricLootTableProvider {
    /** Same key the entity type uses: "<namespace>:entities/<entity id>". */
    public static final RegistryKey<LootTable> GOLDEN_SILVERFISH = RegistryKey.of(RegistryKeys.LOOT_TABLE,
            Identifier.of(GoldenScarabMod.MOD_ID, "entities/golden_silverfish"));

    public ModEntityLootTableProvider(FabricDataOutput output, CompletableFuture<RegistryWrapper.WrapperLookup> registryLookup) {
        super(output, registryLookup, LootContextTypes.ENTITY);
    }

    @Override
    public void accept(BiConsumer<RegistryKey<LootTable>, LootTable.Builder> exporter) {
        // 1-2 gold nuggets, always. The chitin is NOT here: the golden silverfish is in the arthropod tag,
        // so ModLootTableModifiers adds it to every arthropod table (this one included).
        exporter.accept(GOLDEN_SILVERFISH, LootTable.builder()
                .pool(LootPool.builder()
                        .rolls(ConstantLootNumberProvider.create(1))
                        .with(ItemEntry.builder(Items.GOLD_NUGGET)
                                .apply(SetCountLootFunction.builder(UniformLootNumberProvider.create(1.0F, 2.0F))))));
    }
}